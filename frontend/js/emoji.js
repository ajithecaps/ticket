export const QUICK_REACTIONS = ["👍", "✅", "👀", "🎉", "😂", "🙏"];

export const ALL_EMOJI = EMOJI.flatMap(([, list]) => list);

export function searchEmoji(query, limit = 40) {
  const q = query.toLowerCase().replace(/^:/, "");
  if (!q) return [];
  const starts = [];
  const contains = [];
  for (const e of ALL_EMOJI) {
    const words = e[1].split(" ");
    if (words.some((w) => w.startsWith(q))) starts.push(e);
    else if (e[1].includes(q)) contains.push(e);
  }
  return [...starts, ...contains].slice(0, limit);
}

const RECENT_KEY = "chat.recentEmoji";
export function recentEmoji() {
  try { return JSON.parse(localStorage.getItem(RECENT_KEY) || "[]").slice(0, 16); } catch { return []; }
}
export function rememberEmoji(e) {
  try {
    const list = [e, ...recentEmoji().filter((x) => x !== e)].slice(0, 16);
    localStorage.setItem(RECENT_KEY, JSON.stringify(list));
  } catch { /* per-viewer only */ }
}
